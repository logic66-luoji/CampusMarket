"""Build the body of Final_Report.pdf from report/Final_Report.md (ReportLab).

Markdown constructs handled: H1/H2/H3, paragraphs, bullet/numbered lists,
pipe tables, fenced code blocks, blockquotes, images, horizontal rules,
inline `code` / **bold** / *italic* / URLs.

Cover is rendered separately (scripts/cover_render.py, template 09) and
merged as page 1 by merge_final.py.
"""
import re
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.lib.enums import TA_LEFT, TA_CENTER
from reportlab.lib import colors
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (BaseDocTemplate, Frame, PageTemplate, Paragraph,
                                Spacer, Table, TableStyle, Image, Preformatted,
                                KeepTogether, CondPageBreak, HRFlowable)

ROOT = Path(__file__).resolve().parents[1]
MD = ROOT / "report" / "Final_Report.md"
OUT = ROOT / "build" / "body.pdf"

# ━━ Cascade Palette (auto-generated by design_engine.py palette-cascade, seed 7) ━━
PAGE_BG      = colors.HexColor('#eff0f1')
SECTION_BG   = colors.HexColor('#f0f1f2')
CARD_BG      = colors.HexColor('#e4e7e8')
TABLE_STRIPE = colors.HexColor('#ebedee')
HEADER_FILL  = colors.HexColor('#334650')
COVER_BLOCK  = colors.HexColor('#5a7886')
BORDER       = colors.HexColor('#b8c8cf')
ICON         = colors.HexColor('#52798c')
ACCENT       = colors.HexColor('#a63648')
TEXT_PRIMARY = colors.HexColor('#1a1b1c')
TEXT_MUTED   = colors.HexColor('#6f7578')
SEM_INFO     = colors.HexColor('#466a8e')

# ── fonts ──
pdfmetrics.registerFont(TTFont('msyh', 'C:/Windows/Fonts/msyh.ttc', subfontIndex=0))
pdfmetrics.registerFont(TTFont('msyhbd', 'C:/Windows/Fonts/msyhbd.ttc', subfontIndex=0))
pdfmetrics.registerFontFamily('msyh', normal='msyh', bold='msyhbd', italic='msyh', boldItalic='msyhbd')

PAGE_W, PAGE_H = A4
MARGIN = 20 * mm
AVAIL = PAGE_W - 2 * MARGIN

def st(name, **kw):
    base = dict(fontName='msyh', fontSize=10.5, leading=16, textColor=TEXT_PRIMARY,
                wordWrap='CJK', spaceBefore=0, spaceAfter=6)
    base.update(kw)
    return ParagraphStyle(name, **base)

S = {
    'h1': st('h1', fontName='msyhbd', fontSize=17, leading=22, spaceBefore=18,
             spaceAfter=4, textColor=HEADER_FILL),
    'h2': st('h2', fontName='msyhbd', fontSize=13, leading=18, spaceBefore=12,
             spaceAfter=5, textColor=TEXT_PRIMARY),
    'h3': st('h3', fontName='msyhbd', fontSize=11.5, leading=16, spaceBefore=10,
             spaceAfter=4, textColor=TEXT_PRIMARY),
    'body': st('body'),
    'list': st('list', leftIndent=14, bulletIndent=4, spaceAfter=3,
               bulletFontName='msyh'),
    'quote': st('quote', fontSize=9.5, leading=14.5, textColor=TEXT_MUTED, spaceAfter=3,
                bulletFontName='msyh'),
    'cell': st('cell', fontSize=9, leading=12.5, spaceAfter=0),
    'cellh': st('cellh', fontName='msyhbd', fontSize=9, leading=12.5,
                textColor=colors.white, spaceAfter=0),
    'code': st('code', fontName='msyh', fontSize=8.5, leading=11.5, spaceAfter=0),
    'caption': st('caption', fontSize=8.5, leading=11, textColor=TEXT_MUTED,
                  alignment=TA_CENTER, spaceAfter=6),
}

def esc(s):
    return s.replace('&', '&').replace('<', '<').replace('>', '>')

def inline(s):
    s = esc(s)
    s = re.sub(r'`([^`]+)`', r'<font face="msyh" color="#334650">\1</font>', s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', s)
    s = re.sub(r'(?<!\*)\*([^*]+?)\*(?!\*)', r'<i>\1</i>', s)
    s = re.sub(r'(https?://[^\s<）」]+)', r'<font color="#466a8e">\1</font>', s)
    return s

def make_table(rows):
    header, body = rows[0], rows[1:]
    ncol = len(header)
    plain = [[re.sub(r'[*`]', '', c) for c in r] for r in rows]
    weights = []
    for i in range(ncol):
        col = [plain[r][i] for r in range(len(plain))]
        longest_word = max((len(tok) for c in col for tok in c.split()), default=5)
        total = max(len(c) for c in col)
        # 不可断词（如 product_id）必须有足够宽度；总长封顶避免长文列过宽
        weights.append(max(longest_word * 2.0, min(total, 45), 8))
    total_w = sum(weights)
    widths = [AVAIL * w / total_w for w in weights]

    data = [[Paragraph(inline(c), S['cellh']) for c in header]]
    for r in body:
        data.append([Paragraph(inline(c), S['cell']) for c in r] +
                    [Paragraph('', S['cell'])] * (ncol - len(r)))
    t = Table(data, colWidths=widths, repeatRows=1, hAlign='CENTER')
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 3.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3.5),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
    ]
    for r in range(1, len(data)):
        if r % 2 == 0:
            style.append(('BACKGROUND', (0, r), (-1, r), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    return t

def make_code(lines):
    text = '\n'.join(lines)
    pre = Preformatted(text, S['code'])
    box = Table([[pre]], colWidths=[AVAIL])
    box.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), SECTION_BG),
        ('BOX', (0, 0), (-1, -1), 0.5, BORDER),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    return box

def make_quote(lines):
    # 把引言块按逻辑分组："- " 开启列表项，缩进续行并入当前项，
    # 空行分隔段落 —— 保证跨行的 **bold** 等行内标记可正确转换。
    items = []
    cur = None  # (kind, [parts])
    for l in lines:
        s = l.rstrip()
        if s.startswith('- '):
            if cur:
                items.append(cur)
            cur = ('b', [s[2:].strip()])
        elif s.strip():
            if cur:
                cur[1].append(s.strip())
            else:
                cur = ('p', [s.strip()])
        elif cur:
            items.append(cur)
            cur = None
    if cur:
        items.append(cur)

    flow = []
    for kind, parts in items:
        text = inline(' '.join(parts))
        if kind == 'b':
            flow.append(Paragraph('<bullet>–</bullet>' + text, S['quote']))
        else:
            flow.append(Paragraph(text, S['quote']))
    bar = Table([[flow]], colWidths=[AVAIL - 8])
    bar.setStyle(TableStyle([
        ('LINEBEFORE', (0, 0), (0, -1), 2, COVER_BLOCK),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 2),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
    ]))
    return bar

def add_image(path, story):
    from PIL import Image as PILImage  # pandas 依赖里已有 pillow
    img_path = ROOT / path
    if not img_path.exists():
        story.append(Paragraph(inline(f'[missing figure: {path}]'), S['caption']))
        return
    with PILImage.open(img_path) as im:
        w, h = im.size
    disp_w = AVAIL
    disp_h = disp_w * h / w
    story.append(Image(str(img_path), width=disp_w, height=disp_h))
    story.append(Paragraph(f'Figure: {img_path.stem}', S['caption']))

def parse(md_text):
    story = []
    lines = md_text.splitlines()
    i = 0
    first_h1_skipped = False
    para_buf = []
    last_list = None  # (Paragraph, [parts], marker)

    def flush_para():
        if para_buf:
            story.append(Paragraph(inline(' '.join(para_buf)), S['body']))
            para_buf.clear()

    while i < len(lines):
        line = lines[i]

        if line.startswith('```'):
            flush_para()
            block = []
            i += 1
            while i < len(lines) and not lines[i].startswith('```'):
                block.append(lines[i])
                i += 1
            i += 1
            story.append(make_code(block))
            story.append(Spacer(1, 8))
            continue

        if line.startswith('|'):
            flush_para()
            rows = []
            while i < len(lines) and lines[i].startswith('|'):
                cells = [c.strip() for c in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-{2,}:?', c) for c in cells):
                    rows.append(cells)
                i += 1
            if rows:
                story.append(make_table(rows))
                story.append(Spacer(1, 8))
            continue

        if line.startswith('> '):
            flush_para()
            q = []
            while i < len(lines) and (lines[i].startswith('> ') or lines[i] == '>'):
                q.append(lines[i].lstrip('> ').rstrip())
                i += 1
            story.append(make_quote(q))
            story.append(Spacer(1, 8))
            continue

        if line.startswith('![]('):
            flush_para()
            add_image(line[4:-1], story)
            i += 1
            continue

        if line.startswith('# '):
            flush_para()
            title = line[2:].strip()
            if not first_h1_skipped:
                first_h1_skipped = True   # 文档主标题由封面承担
            else:
                story.append(CondPageBreak(0.25 * PAGE_H))
                story.append(Paragraph(inline(title), S['h1']))
                story.append(HRFlowable(width='100%', thickness=1.2,
                                        color=COVER_BLOCK, spaceAfter=8))
            i += 1
            continue

        if line.startswith('## '):
            flush_para()
            story.append(Paragraph(inline(line[3:].strip()), S['h2']))
            i += 1
            continue

        if line.startswith('### '):
            flush_para()
            story.append(Paragraph(inline(line[4:].strip()), S['h3']))
            i += 1
            continue

        if line.strip() == '---':
            flush_para()
            story.append(HRFlowable(width='100%', thickness=0.6,
                                    color=BORDER, spaceBefore=6, spaceAfter=6))
            i += 1
            continue

        m = re.match(r'^(\s*)([-*]|\d+\.)\s+(.*)$', line)
        if m:
            flush_para()
            marker = '•' if m.group(2) in '-*' else m.group(2)
            item = Paragraph(f'<bullet>{marker}</bullet>' + inline(m.group(3)), S['list'])
            story.append(item)
            last_list = (item, [m.group(3)], marker)
            i += 1
            continue

        # 列表项的缩进续行（如参考文献换行、斜体跨行）：并入上一列表项
        if line.strip() and line[:1] in ' \t' and last_list is not None:
            item, parts, marker = last_list
            parts.append(line.strip())
            new = Paragraph(f'<bullet>{marker}</bullet>' + inline(' '.join(parts)), S['list'])
            story[story.index(item)] = new
            last_list = (new, parts, marker)
            i += 1
            continue

        if line.strip():
            para_buf.append(line.strip())
        else:
            flush_para()
        i += 1

    flush_para()
    return story

def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont('msyh', 8.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawCentredString(PAGE_W / 2, 12 * mm, f'{canvas.getPageNumber()}')
    canvas.restoreState()

def main():
    md = MD.read_text(encoding='utf-8')
    story = parse(md)
    doc = BaseDocTemplate(str(OUT), pagesize=A4,
                          leftMargin=MARGIN, rightMargin=MARGIN,
                          topMargin=18 * mm, bottomMargin=18 * mm,
                          title='CampusMarket — A Campus Second-hand Trading Platform (Final Report)',
                          author='Wang Fangcheng, Cai Haoneng, Li Jijia',
                          subject='Database Systems · Track 1 — Database Application Development',
                          creator='CampusMarket project')
    frame = Frame(MARGIN, 18 * mm, AVAIL, PAGE_H - 36 * mm, id='main')
    doc.addPageTemplates([PageTemplate(id='page', frames=[frame], onPage=footer)])
    doc.build(story)
    print('body written:', OUT)

if __name__ == '__main__':
    main()
